/**
 * The license matcher's hashed requirements file (ADR 0142, section 1): compiled by uv for the
 * pinned interpreter on Linux x86_64, wheels only, every package pinned and hashed, ScanCode at
 * the version the review records, and pluggy capped below 1.6.
 */

import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import {
  LICENSE_MATCHER_VERSION,
  SCANCODE_PYTHON,
  SCANCODE_REQUIREMENTS_PATH,
  SCANCODE_TOOLKIT_VERSION,
  reproduceCommands,
  scancodeRequirementsUrl,
} from "../shared/license-file";

const ROOT = join(import.meta.dir, "..");
const TXT = readFileSync(join(ROOT, SCANCODE_REQUIREMENTS_PATH), "utf8");
const IN = readFileSync(join(ROOT, "scripts/ci/scancode-requirements.in"), "utf8");

/** Each requirement: its `name==version` line and the hashes under it. */
function requirements(text: string): { name: string; version: string; hashes: string[] }[] {
  const out: { name: string; version: string; hashes: string[] }[] = [];
  for (const line of text.split("\n")) {
    const pin = /^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s\\;]+)/.exec(line);
    if (pin) {
      out.push({ name: (pin[1] as string).toLowerCase(), version: pin[2] as string, hashes: [] });
      continue;
    }
    const hash = /^\s+--hash=sha256:([0-9a-f]{64})/.exec(line);
    if (hash) out.at(-1)?.hashes.push(hash[1] as string);
  }
  return out;
}

const REQS = requirements(TXT);

describe("scripts/ci/scancode-requirements.txt", () => {
  test("its header is uv's, for the pinned interpreter on Linux x86_64, hashed, wheels only", () => {
    const header = TXT.split("\n").slice(0, 2).join("\n");
    expect(header).toContain("autogenerated by uv");
    expect(header).toContain("uv pip compile scancode-requirements.in");
    expect(header).toContain(`--python-version ${SCANCODE_PYTHON}`);
    expect(header).toContain("--python-platform x86_64-manylinux_2_28");
    expect(header).toContain("--generate-hashes");
    expect(header).toContain("--no-build");
  });

  test("it pins 80 packages, each to one version with at least one SHA-256", () => {
    expect(REQS).toHaveLength(80);
    expect(new Set(REQS.map((r) => r.name)).size).toBe(80);
    for (const r of REQS) expect(r.hashes.length, r.name).toBeGreaterThan(0);
  });

  test("every non-comment line is a pin or a hash: no index, no URL, no editable, no option", () => {
    for (const line of TXT.split("\n")) {
      const t = line.trim();
      if (t === "" || t.startsWith("#")) continue;
      expect(
        /^[A-Za-z0-9][A-Za-z0-9._-]*==\S+ \\$/.test(t) ||
          /^--hash=sha256:[0-9a-f]{64}( \\)?$/.test(t),
        t,
      ).toBe(true);
    }
  });

  test("ScanCode is the version the review records", () => {
    expect(REQS.find((r) => r.name === "scancode-toolkit")?.version).toBe(SCANCODE_TOOLKIT_VERSION);
    expect(LICENSE_MATCHER_VERSION).toBe(`scancode-${SCANCODE_TOOLKIT_VERSION}+spdx-3.27`);
  });

  test("pluggy is below 1.6 (1.7 fails ScanCode 32.5.0 at start)", () => {
    const pluggy = REQS.find((r) => r.name === "pluggy");
    expect(pluggy).toBeDefined();
    const [major, minor] = (pluggy?.version ?? "").split(".").map(Number);
    expect((major as number) < 1 || ((major as number) === 1 && (minor as number) < 6)).toBe(true);
  });

  test("the input file names exactly those two pins", () => {
    const pins = IN.split("\n")
      .map((l) => l.trim())
      .filter((l) => l !== "" && !l.startsWith("#"));
    expect(pins).toEqual([`scancode-toolkit==${SCANCODE_TOOLKIT_VERSION}`, "pluggy<1.6"]);
  });
});

describe("the depositor's reproduction", () => {
  test("names the interpreter, the hashed file at the CLI's tag and the review's options", () => {
    const [venv, install, scan] = reproduceCommands("/data/my set/LICENSE", "0.10.50");
    expect(venv).toBe(`uv venv --python ${SCANCODE_PYTHON} scancode-env`);
    expect(install).toBe(
      "uv pip install --python scancode-env --require-hashes --no-build -r https://raw.githubusercontent.com/nemarOrg/nemar-cli/v0.10.50/scripts/ci/scancode-requirements.txt",
    );
    expect(scan).toBe(
      "scancode-env/bin/scancode --license --license-text --license-text-diagnostics --copyright --processes 1 --timeout 120 --json - '/data/my set/LICENSE'",
    );
    expect(scancodeRequirementsUrl("1.2.3")).toEndWith(`/v1.2.3/${SCANCODE_REQUIREMENTS_PATH}`);
  });

  test("a path with a quote in it stays one shell word", () => {
    const scan = reproduceCommands("/d/it's/LICENSE", "1.0.0")[2] as string;
    expect(scan.endsWith(`'/d/it'\\''s/LICENSE'`)).toBe(true);
  });
});
