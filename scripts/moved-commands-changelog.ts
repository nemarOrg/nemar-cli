/**
 * The CHANGELOG list of every moved and retired admin path, generated from the one table
 * (`MOVED_COMMANDS` in src/lib/moved-commands.ts) so the release note cannot drift from what the
 * CLI does. The list sits in CHANGELOG.md between the two marker comments below;
 * `test/moved-commands-changelog.unit.test.ts` fails when it no longer matches the table.
 *
 *   bun scripts/moved-commands-changelog.ts           print the list
 *   bun scripts/moved-commands-changelog.ts --write   rewrite it in CHANGELOG.md, between the markers
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MOVED_COMMANDS, type MovedCommand } from "../src/lib/moved-commands";

export const START_MARKER =
  "<!-- moved-commands:start (generated by scripts/moved-commands-changelog.ts) -->";
export const END_MARKER = "<!-- moved-commands:end -->";

/** One Markdown list item per row, in table order. */
export function renderMovedCommands(rows: readonly MovedCommand[] = MOVED_COMMANDS): string {
  return rows
    .map((row) =>
      "retired" in row
        ? `- \`nemar admin ${row.oldPath}\`: retired. ${row.retired.charAt(0).toUpperCase()}${row.retired.slice(1)}`
        : `- \`nemar admin ${row.oldPath}\` -> \`nemar admin ${row.newPath}\``,
    )
    .join("\n");
}

/** The text between the markers in `changelog`, or null when either marker is missing. */
export function generatedBlock(changelog: string): string | null {
  const start = changelog.indexOf(START_MARKER);
  const end = changelog.indexOf(END_MARKER);
  if (start < 0 || end < start) return null;
  return changelog.slice(start + START_MARKER.length, end).trim();
}

if (import.meta.main) {
  const list = renderMovedCommands();
  if (process.argv.includes("--write")) {
    const path = join(import.meta.dir, "..", "CHANGELOG.md");
    const text = readFileSync(path, "utf-8");
    const start = text.indexOf(START_MARKER);
    const end = text.indexOf(END_MARKER);
    if (start < 0 || end < start) {
      console.error("CHANGELOG.md has no moved-commands markers");
      process.exit(1);
    }
    writeFileSync(
      path,
      `${text.slice(0, start + START_MARKER.length)}\n${list}\n${text.slice(end)}`,
    );
  } else {
    console.log(list);
  }
}
