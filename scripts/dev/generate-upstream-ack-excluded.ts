#!/usr/bin/env bun
/**
 * Generate `shared/upstream-ack-excluded.ts` from the publication-queue measurement
 * (`.context/plans/publication-queue/d2-blockers.json`, card D2), so the Worker bundles two short
 * id lists instead of the whole measurement (card D3). The ids are read by `readD2Exclusions`, the
 * same fail-closed reader the module's test runs against the JSON.
 *
 *   bun scripts/dev/generate-upstream-ack-excluded.ts
 *
 * The module is written, then formatted by Biome. test/upstream-ack.unit.test.ts fails when the
 * module and the JSON disagree.
 */

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readD2Exclusions } from "../../shared/upstream-ack";

export const SOURCE_PATH = ".context/plans/publication-queue/d2-blockers.json";
export const MODULE_PATH = "shared/upstream-ack-excluded.ts";

/** The module's text, from the measurement's text. */
export function renderModule(jsonText: string): string {
  const doc = JSON.parse(jsonText) as { generatedAt?: unknown };
  const { measured, excluded } = readD2Exclusions(doc);
  if (typeof doc.generatedAt !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(doc.generatedAt)) {
    throw new Error("d2-blockers: no generatedAt date");
  }
  const list = (ids: ReadonlySet<string>) =>
    [...ids]
      .sort()
      .map((id) => `    "${id}",`)
      .join("\n");
  return `/**
 * GENERATED by scripts/dev/generate-upstream-ack-excluded.ts from
 * ${SOURCE_PATH}; do not edit.
 * The batch acknowledgment's exclusions (card D3): the datasets the publication-queue measurement
 * read, and those of them holding an image or document file named as a photo, a face or a
 * questionnaire (in the commit or in its history). test/upstream-ack.unit.test.ts checks this
 * module against the JSON.
 */

export const UPSTREAM_ACK_EXCLUSIONS = {
  generatedOn: "${doc.generatedAt}",
  source: "${SOURCE_PATH}",
  excluded: [
${list(excluded)}
  ],
  measured: [
${list(measured)}
  ],
} as const;
`;
}

if (import.meta.main) {
  const root = join(import.meta.dir, "..", "..");
  writeFileSync(
    join(root, MODULE_PATH),
    renderModule(readFileSync(join(root, SOURCE_PATH), "utf-8")),
  );
  const fmt = spawnSync("bunx", ["biome", "format", "--write", MODULE_PATH], {
    cwd: root,
    stdio: "inherit",
  });
  if (fmt.status !== 0) process.exit(1);
  console.log(`wrote ${MODULE_PATH}`);
}
